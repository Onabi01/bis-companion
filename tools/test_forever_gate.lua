-- Run from the repository root with Lua 5.1.
dofile("ForeverMapping.lua")
dofile("ForeverData.lua")
assert(BiSCompanionForeverGearReady == false)
dofile("ForeverPreRaidLot1.lua")
dofile("ForeverPreRaidGear.lua")
assert(BiSCompanionForeverGearReady == false, "partial lot must stay inactive")
assert(#BiSCompanionBisData["Warrior_Arms"] == 0)
dofile("ForeverPreRaidLot2.lua")
dofile("ForeverPreRaidLot3.lua")
assert(BiSCompanionForeverPreRaidStaging["Druid_FeralTank"])
assert(#BiSCompanionForeverPreRaidStaging["Druid_FeralTank"] >= 12)
dofile("ForeverPreRaidGear.lua")
assert(BiSCompanionForeverGearReady == true, "complete set must activate")
assert(#BiSCompanionBisData["Warrior_Arms"] == 16)
assert(#BiSCompanionBisData["Druid_FeralTank"] >= 12)
assert(#BiSCompanionBisData["Druid_Feral"] >= 12)
assert(BiSCompanionBisData["Druid_FeralTank"] ~= BiSCompanionBisData["Druid_Feral"])
assert(BiSCompanionForeverPreRaidStaging == nil)

